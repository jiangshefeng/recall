import { test, expect } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { MemoryStore } from "../src/lib/store";
import { demoEmbedding } from "../src/lib/similarity";

test("stage evidence opens archived originals on demand and remains scope isolated", async ({ page, request }) => {
  const scope = `stage_${Date.now()}`;
  const snapshot = await (await request.get(`/api/memories?scope=${scope}`)).json();
  const question = "阶段项目的缓存多久过期？";
  const stage = { id: `${scope}-stage`, content: "阶段项目缓存当前8分钟，旧值5分钟已于2026年10月27日被替代。", sourceIds: Array.from({ length: 11 }, (_, i) => `${scope}-r${i}`), createdAt: "2026-10-27T00:00:00Z" };
  const store = new MemoryStore(resolve("data/e2e-rag.sqlite"));
  for (const id of stage.sourceIds) store.saveRecord({ id, scope, question: `归档原文 ${id}`, answer: "完整原始回答", context: "完整原始上下文", createdAt: stage.createdAt });
  store.saveMemory({ id: `${scope}-memory`, scope, summary: "阶段项目缓存8分钟", vector: demoEmbedding(question), space: snapshot.config.space, status: "hot", sourceIds: stage.sourceIds, parentIds: [], reason: "浏览器阶段摘要测试", createdAt: stage.createdAt, stage });
  store.close();
  expect((await request.get(`/api/archive?scope=other&stageId=${stage.id}`)).status()).toBe(404);
  let chatRequests = 0;
  page.on("request", req => { if (req.url().endsWith("/api/chat")) chatRequests++; });
  await page.goto("/");
  await page.getByRole("button", { name: "模型与配置" }).click();
  await page.getByLabel("空间名称").fill(scope);
  await page.getByRole("button", { name: "切换", exact: true }).click();
  await page.getByRole("button", { name: "记忆对话" }).click();
  await page.getByLabel("输入问题").fill(question);
  await page.getByRole("button", { name: "发送", exact: false }).click();
  await expect(page.locator(".message.assistant")).toContainText("当前8分钟");
  const panel = page.locator(".retrieval-panel");
  await panel.locator("summary").filter({ hasText: "[1] 阶段摘要" }).click();
  await panel.locator("summary").filter({ hasText: "阶段摘要 · 覆盖 11 条原文" }).click();
  await panel.getByRole("button", { name: "展开归档原文" }).click();
  await expect(panel.locator("summary").filter({ hasText: "归档原文" })).toHaveCount(11);
  expect(chatRequests).toBe(1);
});

test("below-threshold candidates are displayed separately from evidence", async ({ page, request }) => {
  const scope = `fallback_${Date.now()}`;
  await request.post("/api/seed", { data: { scope } });
  const evidence = await (await request.post("/api/search", { data: { scope, query: "zzzzzzzz", strategy: "expand" } })).json();
  expect(evidence.suggestions).toHaveLength(3);
  expect(evidence.context).toHaveLength(0);
  await page.route("**/api/chat", route => route.fulfill({ json: { answer: "没有相关历史证据。", evidence, memory: { message: "展示验证" }, elapsedMs: 1 } }));
  await page.goto("/");
  await expect(page.getByRole("combobox", { name: "检索策略" })).toHaveCount(0);
  await expect(page.getByText("关联检索 · 自动追溯原文")).toBeVisible();
  await page.getByLabel("输入问题").fill("zzzzzzzz");
  await page.getByRole("button", { name: "发送", exact: false }).click();
  const suggestions = page.getByTestId("low-score-suggestions");
  await expect(suggestions).toBeVisible();
  await expect(suggestions.locator(".hit-card")).toHaveCount(3);
  await expect(suggestions).toContainText("未作为证据发送给模型");
  await expect(page.getByTestId("prompt-excerpt")).toHaveCount(0);
});

test("demo chat, provenance, merge, retrieval modes, and responsive layout", async ({ page, request }) => {
  const scope = `check_${Date.now()}`;
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await expect(page.getByText("演示模式", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "模型与配置" }).click();
  await page.getByLabel("空间名称").fill(scope);
  await page.getByRole("button", { name: "切换", exact: true }).click();
  await page.getByRole("button", { name: "载入示例" }).click();
  await expect(page.getByRole("status")).toContainText("示例已就绪");
  const before = await (await request.get(`/api/memories?scope=${scope}`)).json();
  expect(before.stats).toEqual({ hot: 4, cold: 2, records: 5 });
  await page.getByRole("button", { name: "记忆对话" }).click();
  await page.getByLabel("输入问题").fill("项目 A 的缓存分别多久过期？");
  await page.getByRole("button", { name: "发送", exact: false }).click();
  await expect(page.locator(".message.assistant")).toHaveCount(1);
  await expect(page.locator(".message.assistant")).toContainText("30 分钟");
  await expect(page.locator(".hit-card").first()).toBeVisible();
  await expect(page.getByTestId("budget-usage")).toContainText("估算");
  await expect(page.getByTestId("expansion-status")).toContainText("已触发第二轮");
  await page.getByLabel("输入问题").fill("项目 A 的缓存分别多久过期？");
  await page.getByRole("button", { name: "发送", exact: false }).click();
  await expect(page.locator(".message.assistant")).toHaveCount(2);
  await expect(page.locator(".memory-note").last()).toContainText("已合并");
  const after = await (await request.get(`/api/memories?scope=${scope}`)).json();
  expect(after.stats).toEqual({ hot: 5, cold: 4, records: 7 });
  const sources = await request.post("/api/search", { data: { scope, query: "项目 A 缓存过期", strategy: "sources" } });
  expect(sources.ok()).toBe(true);
  const sourceData = await sources.json();
  expect(sourceData.second).toHaveLength(0);
  expect(sourceData.records.length).toBeGreaterThan(0);
  expect(sourceData.trace.reason).toBe("sources-only");
  expect(sourceData.trace.usage.records).toBe(sourceData.context.length);
  expect(sourceData.trace.usage.estimatedTokens).toBeLessThanOrEqual(6000);
  expect(JSON.stringify(sourceData.context).length).toBeLessThanOrEqual(18000);
  expect(sourceData.context.map((x: { id: string }) => x.id)).toEqual(sourceData.records.map((x: { id: string }) => x.id));
  const empty = await (await request.get(`/api/memories?scope=empty_${scope}`)).json();
  expect(empty.stats.records).toBe(0);
  const invalid = await request.post("/api/search", { data: { scope: "../wrong", query: "test" } });
  expect(invalid.status()).toBe(400);
  await page.setViewportSize({ width: 1440, height: 1050 });
  mkdirSync("artifacts", { recursive: true });
  await page.screenshot({ path: "artifacts/desktop.png", fullPage: true });
  await page.getByRole("button", { name: /记忆库/ }).click();
  await page.getByRole("button", { name: /冷区历史/ }).click();
  await expect(page.locator(".memory-card")).toHaveCount(4);
  await page.getByRole("button", { name: "追溯来源" }).first().click();
  await expect(page.locator(".provenance")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "记忆对话" }).click();
  await page.getByRole("button", { name: "新对话", exact: true }).click();
  await page.screenshot({ path: "artifacts/mobile.png", fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  expect(errors).toEqual([]);
});
